#pragma once

#include "core/io/resource.h"
#include "core/templates/hash_map.h"
#include "core/templates/hash_set.h"
#include "scene/3d/light_probe_data.h"
#include "scene/3d/lightmapper.h"
#include "scene/3d/visual_instance_3d.h"

// Editable placement data. Lighting and interpolation topology have separate
// lifetimes and must not be generated by resource setters or interactive dragging.
class LightProbeVolumeData : public Resource {
	GDCLASS(LightProbeVolumeData, Resource);

	PackedVector3Array positions;
	PackedInt32Array probe_ids;
	HashMap<int, int> probe_indices;
	Dictionary grid_origins;
	int64_t next_id = 0;
	uint64_t revision = 0;

protected:
	static void _bind_methods();

public:
	enum { MAX_PROBES = 65536 };
	Dictionary get_layout() const;
	void set_layout(const Dictionary &p_layout);
	PackedVector3Array get_positions() const { return positions; }
	PackedInt32Array get_probe_ids() const { return probe_ids; }
	int get_probe_count() const { return positions.size(); }
	int find_probe(int p_id) const;
	bool is_custom_probe(int p_id) const;
	bool has_custom_probes() const;
	Vector3 get_probe_position(int p_id) const;
	void set_probe_position(int p_id, Vector3 p_position);
	int add_probe(Vector3 p_position);
	void remove_probe(int p_id);
	int64_t get_next_id() const { return next_id; }
	uint64_t get_revision() const { return revision; }
	LightProbeVolumeData();
};

class LightProbeSystem;
class LightProbeGeometry;

class LightProbeVolume : public Node3D {
	GDCLASS(LightProbeVolume, Node3D);

	Ref<LightProbeVolumeData> probe_data;
	Vector3 size = Vector3(8, 4, 8);
	real_t spacing = 2.0;
	ObjectID registered_system;
	bool enabled = true;
	HashMap<int, int> validation_results;
	bool validation_stale = false;

	void _data_changed();
	void _update_system();

protected:
	static void _bind_methods();
	void _notification(int p_what);

public:
	enum ValidationStatus {
		VALIDATION_UNCHECKED,
		VALIDATION_VALID,
		VALIDATION_INSIDE_GEOMETRY,
		VALIDATION_TOO_CLOSE,
		VALIDATION_AMBIGUOUS,
	};
	ValidationStatus get_probe_validation_status(int p_id) const;
	String get_probe_validation_reason(int p_id) const;
	String get_validation_summary() const;
	void clear_validation();
	void mark_validation_stale();
	void apply_validation(const PackedInt32Array &p_ids, const PackedInt32Array &p_results);
	void set_data(const Ref<LightProbeVolumeData> &p_data);
	Ref<LightProbeVolumeData> get_data() const { return probe_data; }
	void set_size(Vector3 p_size);
	Vector3 get_size() const { return size; }
	void set_spacing(real_t p_spacing);
	real_t get_spacing() const { return spacing; }
	void set_enabled(bool p_enabled);
	bool is_enabled() const { return enabled; }
	LightProbeSystem *get_system() const;
	Dictionary create_grid_layout(bool p_preserve_custom = false) const;
	Dictionary create_filtered_grid_layout(Node *p_geometry_root, bool p_preserve_custom = false, Lightmapper::BakeStepFunc p_step = nullptr, void *p_userdata = nullptr) const;
	void generate_grid(bool p_preserve_custom = false);
	PackedStringArray get_configuration_warnings() const override;
	LightProbeVolume();
	~LightProbeVolume();
};

class LightmapGI;

class LightProbeSystem : public VisualInstance3D {
	GDCLASS(LightProbeSystem, VisualInstance3D);
	friend class LightProbeVolume;

	HashSet<ObjectID> volumes;
	uint64_t revision = 0;
	bool update_queued = false;
	real_t surface_clearance = 0.05;

	Ref<LightProbeData> baked_data;
	Transform3D capture_transform;
	uint32_t baked_layout_signature = 0;
	bool has_layout_signature = false;
	void _baked_data_changed();
	void _refresh_capture_instance();
	uint32_t _get_layout_signature() const;

	void _register_volume(LightProbeVolume *p_volume);
	void _unregister_volume(LightProbeVolume *p_volume);
	void _placement_changed();
	void _emit_placement_changed();

protected:
	static void _bind_methods();
	void _notification(int p_what);
	bool _set(const StringName &p_name, const Variant &p_value);

public:
	void set_light_data(const Ref<LightProbeData> &p_data);
	Ref<LightProbeData> get_light_data() const { return baked_data; }
	void set_capture_transform(const Transform3D &p_transform);
	Transform3D get_capture_global_transform() const;
	Dictionary get_bake_state() const;
	void set_bake_state(const Dictionary &p_state);
	void mark_layout_baked();
	void clear_probe_cache();
	AABB get_aabb() const override;
	LightmapGI *get_bake_source() const;
	void set_surface_clearance(real_t p_clearance);
	real_t get_surface_clearance() const { return surface_clearance; }
	Error prepare_bake(LightProbeGeometry &p_geometry, const Transform3D &p_bake_transform, Vector<Vector3> &r_points, Lightmapper::BakeStepFunc p_step = nullptr, void *p_userdata = nullptr);
	TypedArray<NodePath> get_volumes() const;
	Dictionary get_probe_layout() const;
	uint64_t get_revision() const { return revision; }
	PackedStringArray get_configuration_warnings() const override;
	LightProbeSystem();
	~LightProbeSystem();
};

VARIANT_ENUM_CAST(LightProbeVolume::ValidationStatus);
